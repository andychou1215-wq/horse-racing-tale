# ---- 狀態(賽前分級)：由疲勞+健康簡化換算 S~D ----
# 對應 狀態與健康.md：「狀態」由健康值+目前疲勞值+精神屬性+賽前調整綜合決定。
# MVP簡化為 健康×0.4 + (100-疲勞)×0.6，只是一個可調的近似公式。
def state_score(health: float, fatigue: float) -> float:
    return health * 0.4 + (100 - fatigue) * 0.6


def state_grade(health: float, fatigue: float) -> str:
    score = state_score(health, fatigue)
    if score >= 85:
        return "S"
    if score >= 70:
        return "A"
    if score >= 50:
        return "B"
    if score >= 30:
        return "C"
    return "D"


